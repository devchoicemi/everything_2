import { HOBBY_TAGS } from '@/lib/compat/config'
import { checkText } from '@/lib/profile/quality'

/**
 * AI-assisted profile drafting.
 *
 * Hard rule, enforced structurally, not just by prompt wording: this module
 * NEVER invents a fact. The short bio and detailed profile are built only
 * from the user's own submitted text — condensed/reformatted, never
 * supplemented. Tags are matched against a fixed, controlled vocabulary
 * (never freely generated), so a tag can only appear if the user's own words
 * plausibly support it.
 *
 * Provider abstraction: if ANTHROPIC_API_KEY is set server-side, drafts are
 * generated by a real model call (still under the same no-fabrication system
 * prompt, and the model is asked to quote/paraphrase only — never add new
 * claims). No key is configured in this environment, so requests
 * transparently use the deterministic local fallback below; both paths
 * return the same shape, including `usedAI` / `provider` so the client and
 * this repo's docs can be honest about which one ran.
 */

const MAX_WORDS = 1000
const MIN_WORDS = 15

const EXTRA_TAG_VOCAB = [
  'Bookworm', 'Foodie', 'Dog lover', 'Cat lover', 'Coffee enthusiast', 'Early riser',
  'Night owl', 'Homebody', 'Traveller', 'Introvert', 'Extrovert', 'Music lover',
]

export function wordCount(text: string): number {
  return text.trim().split(/\s+/).filter(Boolean).length
}

export interface DraftInput {
  rawText: string
  /** already-selected structured tags to keep (never overwritten, only added to) */
  existingTags?: string[]
}

export interface ProfileDraft {
  shortBio: string
  detailedProfile: string
  suggestedTags: string[]
  usedAI: boolean
  provider: 'anthropic' | 'local-extractive'
}

export class DraftValidationError extends Error {}

export function validateRawText(rawText: string): void {
  const words = wordCount(rawText)
  if (words < MIN_WORDS) {
    throw new DraftValidationError(`Write at least ${MIN_WORDS} words so there's enough to work with.`)
  }
  if (words > MAX_WORDS) {
    throw new DraftValidationError(`Keep it to ${MAX_WORDS} words or fewer (currently ${words}).`)
  }
  const quality = checkText(rawText, { minWords: MIN_WORDS, maxWords: MAX_WORDS })
  if (!quality.ok && quality.message) throw new DraftValidationError(quality.message)
}

function splitSentences(text: string): string[] {
  return text
    .replace(/\s+/g, ' ')
    .trim()
    .split(/(?<=[.!?])\s+/)
    .filter(Boolean)
}

function extractiveShortBio(rawText: string): string {
  const sentences = splitSentences(rawText)
  let bio = ''
  for (const s of sentences) {
    if ((bio + ' ' + s).trim().length > 260) break
    bio = (bio + ' ' + s).trim()
    if (bio.length > 140) break
  }
  return bio || sentences[0] || rawText.slice(0, 200)
}

function cleanedDetailedProfile(rawText: string): string {
  return rawText
    .replace(/[ \t]+/g, ' ')
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .filter(Boolean)
    .join('\n\n')
}

function matchTags(rawText: string, existingTags: string[]): string[] {
  const lower = rawText.toLowerCase()
  const vocab = [...HOBBY_TAGS, ...EXTRA_TAG_VOCAB]
  const matched = vocab.filter((tag) => lower.includes(tag.toLowerCase().replace(/s$/, '')))
  return Array.from(new Set([...existingTags, ...matched])).slice(0, 10)
}

function localExtractiveDraft(input: DraftInput): ProfileDraft {
  return {
    shortBio: extractiveShortBio(input.rawText),
    detailedProfile: cleanedDetailedProfile(input.rawText),
    suggestedTags: matchTags(input.rawText, input.existingTags ?? []),
    usedAI: false,
    provider: 'local-extractive',
  }
}

const SYSTEM_PROMPT = `You help a dating-profile owner tighten their own writing. Rules:
- Use ONLY facts, phrases and claims present in the user's text.
- NEVER invent a detail, name, number, place, or preference that isn't stated.
- Produce a short bio (<= 240 characters) and a longer detailed profile, both in the user's own voice.
- Return strict JSON: {"shortBio": string, "detailedProfile": string, "suggestedTags": string[]}.
- suggestedTags must only contain items from the provided tag vocabulary that the text actually supports.`

async function anthropicDraft(input: DraftInput, apiKey: string): Promise<ProfileDraft> {
  const vocab = [...HOBBY_TAGS, ...EXTRA_TAG_VOCAB]
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'x-api-key': apiKey,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model: 'claude-sonnet-5',
      max_tokens: 800,
      system: SYSTEM_PROMPT,
      messages: [
        {
          role: 'user',
          content: `Tag vocabulary (use only these, only if supported by the text): ${vocab.join(', ')}\n\nUser's text:\n${input.rawText}`,
        },
      ],
    }),
  })

  if (!res.ok) {
    throw new Error(`AI provider error: ${res.status}`)
  }

  const data = (await res.json()) as { content?: { type: string; text?: string }[] }
  const text = data.content?.find((c) => c.type === 'text')?.text ?? '{}'
  const parsed = JSON.parse(text) as Partial<ProfileDraft>

  return {
    shortBio: parsed.shortBio ?? extractiveShortBio(input.rawText),
    detailedProfile: parsed.detailedProfile ?? cleanedDetailedProfile(input.rawText),
    suggestedTags: (parsed.suggestedTags ?? []).filter((t) => vocab.includes(t)),
    usedAI: true,
    provider: 'anthropic',
  }
}

export async function generateProfileDraft(input: DraftInput): Promise<ProfileDraft> {
  validateRawText(input.rawText)

  const apiKey = process.env.ANTHROPIC_API_KEY
  if (apiKey) {
    try {
      return await anthropicDraft(input, apiKey)
    } catch {
      // Provider hiccup — degrade to the deterministic fallback rather than
      // fail the whole request; still never fabricates anything.
      return localExtractiveDraft(input)
    }
  }

  return localExtractiveDraft(input)
}
